// Arduino calls setup() once at power-on / after reset.
void setup() {
    Serial.begin(115200);          // USB — debug log (visible in `pio device monitor`)
    Serial1.begin(9600);           // Hardware UART on D18/D19 — talks to the HC-05.
                                   // 9600 must match what we set with AT+UART
                                   // when configuring the modules.

    // Tell the Servo library which pin to drive for each joint. `.attach()`
    // hooks the pin into the library's internal 50 Hz pulse generator.
    servoBase.attach(SERVO_PIN_BASE);
    servoShoulder.attach(SERVO_PIN_SHOULDER);
    servoElbow.attach(SERVO_PIN_ELBOW);
    servoClaw.attach(SERVO_PIN_CLAW);

    // Move to the safe starting pose immediately so the arm doesn't sit
    // at whatever random angle the servos last held.
    for (auto& a : axes) a.servo.write(a.lim.initial);

    // E-stop rocker, read with the internal pull-up (see ESTOP_PIN notes).
    // Seed the debounce timer + latch the initial state so we boot stopped if
    // the rocker is already in the E-STOP position.
    pinMode(ESTOP_PIN, INPUT_PULLUP);
    estopRunSinceMs = millis();
    updateEstop();

    // F("...") stores the string in flash (program memory) instead of RAM.
    // RAM is precious on the Mega (8 KB) — every F() saves a few bytes.
    Serial.println(F("[arm] boot OK — Serial1=HC-05@9600"));
    lastFrameMs = millis();
    lastTickMs  = millis();
}

// Arduino calls loop() over and over, as fast as it can, forever.
void loop() {
    // 0. Poll the e-stop rocker first, so the rest of the loop sees a fresh
    //    estopEngaged. When engaged it overrides everything below.
    updateEstop();

    // 1. Drain the Bluetooth receive buffer. `Serial1.available()` returns
    //    how many unread bytes are sat in the UART's hardware FIFO. We
    //    feed each one to the decoder; it returns true when it has a
    //    complete, checksum-valid 7-byte frame. While e-stopped we still drain
    //    the FIFO (so it can't overflow) but ignore the frames.
    while (Serial1.available()) {
        ArmProto::Frame f;
        if (decoder.feed((uint8_t)Serial1.read(), f) && !estopEngaged) {
            applyFrame(f);
        }
    }

    logPositions();

    // Pose report back to the controller (bumpless handoff). At ~15 Hz, send
    // our actual current pose over the HC-05 with FLAG_AUTO set whenever the
    // arm is driving itself, so the controller can track us and a switch back
    // to manual doesn't jump. The HC-05 SPP link is full-duplex, so this
    // shares the wire with the controller's command stream fine.
    static uint32_t lastPoseTxMs = 0;
    if (millis() - lastPoseTxMs >= 66) {
        lastPoseTxMs = millis();
        ArmProto::Frame pf;
        pf.base     = (uint8_t)(axes[0].current + 0.5f);
        pf.shoulder = (uint8_t)(axes[1].current + 0.5f);
        pf.elbow    = (uint8_t)(axes[2].current + 0.5f);
        pf.claw     = (uint8_t)(axes[3].current + 0.5f);
        // Mark the pose "autonomous" while e-stopped too, so the controller
        // tracks the held pose and resumes bumplessly when the rocker clears.
        const bool autonomous = seqAutoMode
                             || homeState != HomeState::IDLE
                             || seqState  != SeqState::IDLE
                             || estopEngaged;
        pf.flags = autonomous ? ArmProto::FLAG_AUTO : 0;
        uint8_t pbuf[ArmProto::FRAME_SIZE];
        ArmProto::encode(pf, pbuf);
        Serial1.write(pbuf, ArmProto::FRAME_SIZE);
    }

    // RX debug dump (temporary) — n=frames this interval, drv=how many read as
    // "driving", then the last frame's angles + decoded flags. n=0 means no BT
    // frames arrived (controller off / unpaired).
    if (g_rxDebug && millis() - g_lastRxDbgMs >= 500) {
        g_lastRxDbgMs = millis();
        Serial.print(F("[rx] n="));     Serial.print(g_rxCount);
        Serial.print(F(" drv="));       Serial.print(g_drvCount);
        Serial.print(F(" b="));         Serial.print(g_lastRx.base);
        Serial.print(F(" s="));         Serial.print(g_lastRx.shoulder);
        Serial.print(F(" e="));         Serial.print(g_lastRx.elbow);
        Serial.print(F(" c="));         Serial.print(g_lastRx.claw);
        Serial.print(F(" flags="));     Serial.print(g_lastRx.flags);
        Serial.print(F(" BTN="));       Serial.print((g_lastRx.flags & ArmProto::FLAG_BUTTON) ? 1 : 0);
        Serial.print(F(" HOME="));      Serial.print((g_lastRx.flags & ArmProto::FLAG_HOME) ? 1 : 0);
        Serial.print(F(" maxd="));      Serial.println(g_lastMaxDelta);
        g_rxCount = 0; g_drvCount = 0;
    }

    // 1c. USB serial commands. One newline-terminated line each (a bare
    //     "p\n", or "b120\n" with an argument) — see handleUsbCommand().
    //     Accumulate bytes into usbBuf until CR/LF, then dispatch. Lines
    //     longer than the buffer are dropped and resync at the next newline.
    while (Serial.available()) {
        int ci = Serial.read();
        if (ci < 0) break;
        char c = (char)ci;
        if (c == '\r' || c == '\n') {
            if (usbLen > 0) {
                usbBuf[usbLen] = '\0';
                handleUsbCommand(usbBuf);
                usbLen = 0;
            }
        } else if (usbLen < sizeof(usbBuf) - 1) {
            usbBuf[usbLen++] = c;
        } else {
            usbLen = 0;     // overflow — drop and resync at next newline
        }
    }

    // 1d. Advance the pickup sequence + staged home. Both no-op when IDLE.
    //     Frozen while e-stopped — holdEstop() owns the targets instead.
    if (!estopEngaged) {
        seqTick();
        homeTick();
    }

    // 2. Every TICK_MS, slew the servos one step toward their targets.
    uint32_t now = millis();
    if (now - lastTickMs >= TICK_MS) {
        uint32_t dt = now - lastTickMs;   // actual elapsed time, used by slewAndWrite
        lastTickMs = now;

        // Link watchdog: if we haven't heard a valid frame for too long,
        // pretend the target is wherever we currently are. The slew step
        // then has zero error, so the arm stops mid-motion instead of
        // sailing on toward the last received target.
        //
        // Suppressed in auto mode: there the Pi (over USB) is the command
        // authority, not the BT link, and a Pi-set target ('v'/'b'/keyframe)
        // can take longer than LINK_TIMEOUT_MS to slew to. We must not freeze
        // it just because the controller is parked or powered off. There's no
        // runaway risk — in auto mode the BT frames aren't driving the arm.
        if (!seqAutoMode && now - lastFrameMs > LINK_TIMEOUT_MS) {
            for (auto& a : axes) a.target = (uint8_t)(a.current + 0.5f);
        }

        // E-stop has the final say on the targets: pin every joint to its
        // current angle (hold) and keep the claw opening. Runs after the
        // watchdog so nothing else can move the arm while engaged.
        if (estopEngaged) holdEstop();

        // Veto shoulder lifts while it's down and the elbow isn't tucked.
        // Runs after the watchdog so a dropped link can't sneak a lift past.
        applyShoulderLiftGate();

        slewAndWrite(dt);
    }
    // Note: nothing else runs in loop(), so this is a tight poll. If you
    // ever add work here, keep it short — anything > a few ms eats into
    // the tick budget and motion gets jerky.
}
